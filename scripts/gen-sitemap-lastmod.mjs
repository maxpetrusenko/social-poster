#!/usr/bin/env node
/**
 * Regenerate `src/lib/site/sitemap-lastmod.generated.ts`.
 *
 * Why this exists: `src/app/sitemap.ts` served `/`, `/blog`, `/docs`,
 * `/social-media-bot` and every `/blog/category/*` URL with NO `<lastmod>` at
 * all, and stamped every blog post with its publish date. A mixed sitemap tells
 * Google nothing about what actually changed, and Google discounts lastmod it
 * finds unreliable — including sitemaps where the values are always the build
 * or run date, or where every URL carries the same date.
 *
 * So each static route's value is `git log -1 --format=%cs -- <the source files
 * that render that route>`, newest wins. Blog posts keep their own publish date
 * and category URLs derive from the newest post in that category (see
 * `src/app/sitemap.ts`), so every URL gets a value derived from ITS OWN
 * history rather than one global stamp.
 *
 * Usage:
 *   node scripts/gen-sitemap-lastmod.mjs           # rewrite the generated file
 *   node scripts/gen-sitemap-lastmod.mjs --check   # exit 1 if it is out of date
 *
 * The output is deterministic for a given route: every route below has real
 * history in this repo, so `--check` does not depend on where HEAD happens to
 * point. The HEAD date is used only as a last-resort fallback for a route with
 * no path history at all.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(REPO_ROOT, "src/lib/site/sitemap-lastmod.generated.ts");

/**
 * route -> every source path that renders that route. Keep in sync with the
 * static entries in `src/app/sitemap.ts`.
 */
const ROUTE_SOURCES = {
  "/": ["src/app/page.tsx", "src/components/landing"],
  "/blog": ["src/app/blog/page.tsx", "src/components/blog", "src/lib/blog"],
  "/docs": ["src/app/docs/page.tsx"],
  "/social-media-bot": ["src/app/social-media-bot/page.tsx"],
};

function git(args) {
  try {
    return execFileSync("git", args, {
      cwd: REPO_ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "";
  }
}

/** Newest `git log -1 --format=%cs -- <path>` across `paths`, or null. */
function gitDateForPaths(paths) {
  const dates = paths.map((p) => git(["log", "-1", "--format=%cs", "--", p])).filter(Boolean).sort();
  return dates.length ? dates[dates.length - 1] : null;
}

const headDate = git(["log", "-1", "--format=%cs"]) || new Date().toISOString().slice(0, 10);

const unresolved = [];
const routeLastmod = {};
for (const [route, paths] of Object.entries(ROUTE_SOURCES)) {
  const date = gitDateForPaths(paths);
  if (!date) unresolved.push(route);
  routeLastmod[route] = date ?? headDate;
}

const latest = Object.values(routeLastmod).sort().pop();

const body = Object.entries(routeLastmod)
  .map(([route, date]) => `  ${JSON.stringify(route)}: ${JSON.stringify(date)},`)
  .join("\n");

const sourceBody = Object.entries(ROUTE_SOURCES)
  .map(([route, paths]) => `  ${JSON.stringify(route)}: [\n${paths.map((p) => `    ${JSON.stringify(p)},`).join("\n")}\n  ],`)
  .join("\n");

const output = `// AUTO-GENERATED by scripts/gen-sitemap-lastmod.mjs — do not edit by hand.
//
// Regenerate with: npm run sitemap:lastmod
// Prove it is in sync: npm run sitemap:lastmod:check
//
// Each static route's date is \`git log -1 --format=%cs\` for the source files
// that render that route, so a sitemap URL reports the date of its OWN last
// significant source change and not a shared build/run timestamp.
/* eslint-disable */

/** static route -> the source paths that render it. */
export const ROUTE_SOURCES: Record<string, string[]> = {
${sourceBody}
};

/** static route -> newest commit date (%cs) among that route's source paths. */
export const ROUTE_LASTMOD: Record<string, string> = {
${body}
};

/**
 * Newest generated value. Last-resort fallback so no sitemap entry can ever be
 * emitted without a lastmod; still source-derived, never the request time.
 */
export const LATEST_ROUTE_LASTMOD = ${JSON.stringify(latest)};
`;

const check = process.argv.includes("--check");
let current = "";
try {
  current = readFileSync(OUT, "utf8");
} catch {
  current = "";
}

if (check) {
  if (current !== output) {
    console.error(`sitemap lastmod is stale: ${OUT} does not match git history.`);
    console.error("Run: npm run sitemap:lastmod");
    process.exit(1);
  }
  console.log(`sitemap lastmod in sync with git history (${Object.keys(routeLastmod).length} static routes).`);
  process.exit(0);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, output);
if (unresolved.length) {
  console.warn(`no path history for ${unresolved.join(", ")} — fell back to HEAD date ${headDate}`);
}
for (const [route, date] of Object.entries(routeLastmod)) {
  console.log(`${route.padEnd(20)} ${date}`);
}
console.log(`\nwrote ${OUT.replace(REPO_ROOT + "/", "")}`);
